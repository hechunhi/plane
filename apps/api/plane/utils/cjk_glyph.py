# 「争」「会」は同形だが表に残しても無害(恒等)。誤字の温床を避けるため
# 恒等マップは走査時に無視する。
_MAP = {k: v for k, v in _MAP.items() if k != v}

_RE = re.compile("[" + "".join(_MAP) + "]")

# 変換しきれない = 字形ではなく中国語の文そのもの、を検知する指標。
# comment.py の判定と同じ思想(簡体にしか出ない字)だが、こちらは
# **語彙・文法語** に絞る — 字形マップで直せないものだけ。
_RESIDUAL = re.compile(r"[们这那么呢吗吧哪咱俩您甭嘛]")


def to_ja(text):
    """日本語のつもりの文に混じった簡体字形を日本語字形へ直す。"""
    if not text:
        return text
    return _RE.sub(lambda m: _MAP[m.group(0)], text)


def has_chinese_residue(text):
    """字形直し後も残る中国語の文法語 = 文ごと中国語、の疑い。"""
    return bool(_RESIDUAL.search(text or ""))
