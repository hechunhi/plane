/**
 * BARSOUL 2026-08 — 複数行の貼り付けを ToDo の並びに直す。
 *
 * この画面に来るやることの多くは、チャットやメモ帳に既に書いてある。
 * それを 1 行ずつ手で写させるなら、人は写さない。だから貼れば行になる。
 * 行頭の "- " や "1. " は貼り元の飾りで、やることの名前では無いので落とす。
 */

/** 一度に貼れる行数。事故で本文まるごと貼った時に、一覧を壊さないための上限。 */
export const PASTE_LIMIT = 50;

// 記号の後ろの空白は **あったり無かったり** する。「・やること」は日本語では
// 空けない方が普通なので、記号の類は空白無しでも落とす。逆に "-" や "1." は
// 空白まで見ないと "-5度" や "1.5倍" を食ってしまうので、そこは厳しくする。
// 絵文字の記号は後ろに異体字セレクタ(U+FE0F)が付いて来る事がある。文字クラスに
// 直接入れると 1 文字として扱われず、見えない字だけ題名に残る。だから外に出す。
const BULLET = /^\s*(?:[-*+]\s+|\d+[.)]\s+|\[[ xX]\]\s*|[·・‣▪◦●○□☐☑✓]\uFE0F?\s*)/;

export const splitPastedLines = (text: string): string[] =>
  text
    .split(/\r?\n/)
    .map((line) => line.replace(BULLET, "").trim())
    .filter(Boolean);
