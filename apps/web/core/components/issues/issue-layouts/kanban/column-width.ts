/**
 * BARSOUL 2026-08 — カンバン列幅の単一情報源.
 *
 * 以前は `default.tsx` と `swimlanes.tsx` に `w-[350px]` が別々に直書きされていた。
 * その後 304px 固定にしたが、固定幅はどの画面でも必ずどちらかが破綻する:
 *   - Windows ノート(CSS 1200〜1400px)では列が太すぎて 3 列で頭打ち
 *   - Mac の高精細ディスプレイ(CSS 1900px 超)では列が全部入ってしまい、
 *     右側が丸ごと死んだ余白になる(盤面が w-max = 列の合計幅で止まるため)
 *
 * なので「固定幅」をやめ、**下限つきの伸びる列**にした。規則は 3 つだけ:
 *
 *   1. 下限 15rem = 240px (`sm:w-[15rem]` + 親の `flex-shrink-0`)
 *      これ以下には絶対に縮まない。足りなければ横スクロール。
 *   2. 余white があれば伸びる (`sm:grow`)
 *      盤面側 (base-kanban-root の `min-w-full`) が必ずスクローラ幅まで広がるので、
 *      列が全部収まる画面では余りを列が均等に吸収する = 右側の死に余白が消える。
 *   3. 上限 20rem = 320px (`sm:max-w-[20rem]`)
 *      天井は「カードの縦横比」で決めた。実測(2560px, 密度は desktop トークン):
 *        384px → カード高 88〜141px = 比 2.7〜4.4:1。タイトル1行+バッジ1行の
 *                カードが横長のスラブになり不格好(2026-08-19 却下)。
 *        320px → カード高 110〜141px = 比 2.2〜2.9:1。カンバンらしい比率。
 *      なので 320px で止める。これより広い画面では右に余白が残るが、
 *      「カードの形が崩れる」より「盤面の右が空く」方がまだ許せる。
 *      余白を左右に振る案(justify-center)も試したが、ヘッダやツールバーが
 *      左寄せなのに盤だけ中央に浮いて見えるので採用しない。
 *
 * 実測(2026-08-19、サイドバー展開 250px、6 グループ):
 *   1200 → 3 列 / 1280 → 4 列 / 1366 → 4 列 / 1440 → 4 列 (いずれも列幅 240px)
 *   1536 → 5 列 240px / 1728 → 6 列 240px
 *   1920 → 6 列 263px(右余白 23px) / 2048 → 6 列 284px(右余白 23px)
 *   2560 → 6 列 320px(天井にあたる。右余白 560px)
 * 天井に当たるのは「余幅 / 列数 > 320px」= 概ね 2260px 超の画面だけなので、
 * Windows ノートの 1200〜1536 帯はこの上限に一切触れない。
 * 1200〜1400 の帯では最狭の 240px、広い画面では自動で太る。段(lg/2xl)は刻んでいない
 * ので「1366 と 1280 で体験が変わる」ことも、特定解像度向けのマジックナンバーもない。
 *
 * スマホ(< 640px)は 1 列 + 次の列の端 1.75rem を覗かせる(Trello と同じ「まだ右に
 * 列があるよ」の合図)。横スクロールできることが一目で分かる。
 * 文字サイズはここでは触っていない(タイポは variables.css のトークン側)。
 */
export const KANBAN_COLUMN_WIDTH_CLASS =
  "w-[calc(100vw-2*var(--padding-page-x)-1.75rem)] sm:w-[15rem] sm:grow sm:max-w-[20rem]";

/** 列同士の横間隔。狭い画面ほど詰める。 */
export const KANBAN_COLUMN_GAP_CLASS = "gap-2 lg:gap-3";

/**
 * BARSOUL 2026-08 — スマホ時だけ列を「へこんだ器」に見せる装飾。
 *
 * Trello のモバイルは列がカードより一段暗い角丸コンテナに入っていて、
 * 「今どの列を見ているか」「カードは何個ぶら下がっているか」が一目で分かる。
 * こちらは列が背景と同色で境界が無く、白いカードが宙に浮いて見えていた。
 *
 * 器の色は既存トークンで決める(マジックカラー禁止):
 *   ページ  bg-surface-2 = oklch(0.9848 …)
 *   器      bg-layer-1   = oklch(0.9696 …)  ← ページより一段沈む
 *   カード  bg-layer-2   = 白               ← 器より必ず浮く
 * 列が 1 列で画面いっぱいになるのは sm 未満だけなので、器も max-sm: に揃える。
 */
export const KANBAN_COLUMN_SURFACE_CLASS = "max-sm:rounded-xl max-sm:bg-layer-1 max-sm:p-1.5";
